
from collections import defaultdict
from fractions import Fraction
from math import gcd, isqrt
from time import perf_counter
import argparse
import csv
import heapq


# ============================================================
# EXACT MATHEMATICS
# ============================================================

def is_square(n):
    if n < 0:
        return False
    r = isqrt(n)
    return r * r == n


def square_gap(n):
    r = isqrt(n)
    return min(n - r*r, (r+1)*(r+1) - n)


def normalized_gap(n):
    """
    Exact distance from sqrt(n) to the nearest integer
    is irrational in general.

    This rational quantity is a useful approximation:
        |n-k^2| / (r+k)
    where r=floor(sqrt(n)), and k is the nearest integer.

    Ranking uses Fraction, not floating-point arithmetic.
    """
    r = isqrt(n)

    if n - r*r <= (r+1)*(r+1) - n:
        k = r
    else:
        k = r+1

    if n == k*k:
        return Fraction(0, 1)

    return Fraction(abs(n-k*k), r+k)


def primitive(a, b, c):
    return gcd(gcd(a, b), c) == 1


# ============================================================
# PYTHAGOREAN GRAPH
# ============================================================

def build_graph(max_edge):
    """
    Complete graph of Pythagorean leg pairs
    with both legs <= max_edge.

    Primitive triples are generated by Euclid's formula;
    all positive multiples are included.
    """
    graph = defaultdict(set)
    primitive_pairs = 0

    m = 2

    while 2*m*m < 3*max_edge:

        for n in range(1, min(m, max_edge // (2*m) + 1)):

            if gcd(m, n) != 1:
                continue

            if (m-n) % 2 == 0:
                continue

            u = m*m - n*n
            v = 2*m*n

            a, b = sorted((u, v))

            if b > max_edge:
                continue

            primitive_pairs += 1

            for k in range(1, max_edge // b + 1):
                x = k*a
                y = k*b

                graph[x].add(y)
                graph[y].add(x)

        m += 1

    return graph, primitive_pairs


# ============================================================
# FAST TRIANGLE ENUMERATION
# ============================================================

def graph_bricks(graph):
    """
    Each graph triangle a < b < c is an Euler brick.
    Return only primitive bricks.
    """
    for a in sorted(graph):

        for b in sorted(x for x in graph[a] if x > a):

            # Iterate over the smaller adjacency set.
            if len(graph[a]) <= len(graph[b]):
                source = graph[a]
                other = graph[b]
            else:
                source = graph[b]
                other = graph[a]

            for c in source:
                if c > b and c in other:
                    if primitive(a, b, c):
                        yield (a, b, c)


# ============================================================
# INDEPENDENT CONTROL SEARCH
# ============================================================

def brute_force_bricks(max_edge):
    """
    Independent verification for small limits.

    Does NOT use Euclid's formula or the graph generator.
    Directly checks whether every pair of edges
    has an integer face diagonal.

    Complexity is O(max_edge^2) for pair construction.
    """
    neighbors = defaultdict(set)

    for a in range(1, max_edge + 1):
        aa = a*a

        for b in range(a+1, max_edge+1):

            if is_square(aa + b*b):
                neighbors[a].add(b)
                neighbors[b].add(a)

    results = set()

    for a in range(1, max_edge+1):
        for b in neighbors[a]:

            if b <= a:
                continue

            for c in neighbors[b]:

                if c <= b:
                    continue

                if c not in neighbors[a]:
                    continue

                if primitive(a, b, c):
                    results.add((a, b, c))

    return results


def verify_small(max_edge):
    print("\nINDEPENDENT VERIFICATION")

    start = perf_counter()

    graph, _ = build_graph(max_edge)

    fast = set(graph_bricks(graph))
    brute = brute_force_bricks(max_edge)

    if fast != brute:
        missing = sorted(brute - fast)
        extra = sorted(fast - brute)

        print("VERIFICATION FAILED")
        print("Missing from graph:", missing[:10])
        print("Extra in graph:", extra[:10])

        raise AssertionError(
            "Graph and brute-force results differ!"
        )

    print(f"Verification bound: {max_edge}")
    print(f"Matching primitive bricks: {len(fast)}")
    print(f"Verification time: {perf_counter()-start:.3f}s")
    print("VERIFICATION PASSED")


# ============================================================
# EXPERIMENT
# ============================================================

def run(max_edge, top, output, verify_bound):

    if verify_bound > 0:
        verify_small(verify_bound)

    start = perf_counter()

    graph, primitive_pairs = build_graph(max_edge)

    graph_time = perf_counter() - start

    vertices = len(graph)
    edges = sum(len(v) for v in graph.values()) // 2

    # Heap contains only the best 'top' results.
    heap = []

    total = 0
    perfect_count = 0

    with open(output, "w", newline="", encoding="utf-8") as f:

        writer = csv.writer(f)

        writer.writerow([
            "a", "b", "c",
            "x", "y", "z",
            "space_squared",
            "space_floor",
            "square_gap",
            "normalized_gap",
            "perfect"
        ])

        for a, b, c in graph_bricks(graph):

            total += 1

            x2 = a*a+b*b
            y2 = a*a+c*c
            z2 = b*b+c*c

            x = isqrt(x2)
            y = isqrt(y2)
            z = isqrt(z2)

            # Exact mathematical verification.
            assert x*x == x2
            assert y*y == y2
            assert z*z == z2
            assert primitive(a, b, c)

            s = a*a+b*b+c*c
            d = isqrt(s)

            gap = square_gap(s)
            norm = normalized_gap(s)

            perfect = d*d == s

            if perfect:
                perfect_count += 1

                assert (
                    a*a+b*b+c*c == d*d
                )

                print("\n*** PERFECT CUBOID FOUND ***")
                print(f"Edges: ({a}, {b}, {c})")
                print(f"Face diagonals: ({x}, {y}, {z})")
                print(f"Space diagonal: {d}")

            writer.writerow([
                a, b, c,
                x, y, z,
                s, d,
                gap,
                f"{float(norm):.12f}",
                int(perfect)
            ])

            # Larger heap key means a better candidate.
            key = (-norm, -gap, -a, -b, -c)
            entry = (key, (a, b, c, gap, norm))

            if len(heap) < top:
                heapq.heappush(heap, entry)

            elif key > heap[0][0]:
                heapq.heapreplace(heap, entry)

    total_time = perf_counter() - start

    print("\n" + "="*65)
    print("EULER BRICK RESEARCH - SEARCH ENGINE v0.5")
    print("="*65)

    print(f"Max edge: {max_edge}")
    print(f"Primitive Pythagorean pairs: {primitive_pairs}")
    print(f"Graph vertices: {vertices}")
    print(f"Graph edges: {edges}")
    print(f"Primitive Euler bricks: {total}")
    print(f"Perfect cuboids: {perfect_count}")

    print("\nPERFORMANCE")
    print(f"Graph construction: {graph_time:.3f} seconds")
    print(f"Total time: {total_time:.3f} seconds")

    print("\nTOP CANDIDATES (normalized ranking)")

    for _, data in sorted(heap, reverse=True):
        a, b, c, gap, norm = data

        print(
            f"({a}, {b}, {c}) "
            f"gap={gap} "
            f"normalized={float(norm):.9f}"
        )

    print(f"\nSaved to: {output}")

    if perfect_count == 0:
        print("No perfect cuboid found in this search.")


# ============================================================
# COMMAND LINE
# ============================================================

if __name__ == "__main__":

    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--max-edge", type=int, default=10000
    )

    parser.add_argument(
        "--top", type=int, default=10
    )

    parser.add_argument(
        "--output", default="search_results.csv"
    )

    parser.add_argument(
        "--verify", type=int, default=300,
        help="Independent brute-force verification limit; "
             "0 disables verification"
    )

    args = parser.parse_args()

    if (
        args.max_edge < 1
        or args.top < 1
        or args.verify < 0
    ):
        parser.error("Invalid parameters.")

    run(
        args.max_edge,
        args.top,
        args.output,
        args.verify
    )
